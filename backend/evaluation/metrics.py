"""Evaluation metrics for pairwise and identity-cluster behavior.

These functions operate on predictions/results already generated by a pipeline;
they never tune a model or select an operating point implicitly.
"""
from __future__ import annotations

from typing import Dict, Iterable, List, Sequence, Tuple

import numpy as np


def roc_points(y_true: Sequence[int], scores: Sequence[float], thresholds: Sequence[float] | None = None):
    y = np.asarray(y_true, dtype=np.int32)
    s = np.asarray(scores, dtype=np.float64)
    if thresholds is None:
        thresholds = sorted(set(float(x) for x in s), reverse=True)
    out = []
    pos = max(1, int(np.sum(y == 1)))
    neg = max(1, int(np.sum(y == 0)))
    for t in thresholds:
        pred = s >= float(t)
        tp = int(np.sum(pred & (y == 1)))
        fp = int(np.sum(pred & (y == 0)))
        fn = int(np.sum(~pred & (y == 1)))
        tn = int(np.sum(~pred & (y == 0)))
        out.append({
            "threshold": float(t),
            "tpr": tp / pos,
            "fpr": fp / neg,
            "precision": tp / max(1, tp + fp),
            "fnr": fn / pos,
            "tnr": tn / neg,
        })
    return out


def eer(y_true: Sequence[int], scores: Sequence[float]) -> float:
    pts = roc_points(y_true, scores)
    return min(abs(p["fpr"] - p["fnr"]) for p in pts) / 2.0 + next(p["fnr"] for p in pts if abs(p["fpr"] - p["fnr"]) == min(abs(q["fpr"] - q["fnr"]) for q in pts)) / 2.0


def tar_at_far(y_true: Sequence[int], scores: Sequence[float], far: float) -> Dict[str, float]:
    points = roc_points(y_true, scores)
    eligible = [p for p in points if p["fpr"] <= far]
    if not eligible:
        return {"far": far, "tar": 0.0, "threshold": float("inf")}
    best = max(eligible, key=lambda p: p["tpr"])
    return {"far": far, "tar": best["tpr"], "threshold": best["threshold"]}


def far_at_tar(y_true: Sequence[int], scores: Sequence[float], tar: float) -> Dict[str, float]:
    points = roc_points(y_true, scores)
    eligible = [p for p in points if p["tpr"] >= tar]
    if not eligible:
        return {"tar": tar, "far": 1.0, "threshold": float("-inf")}
    best = min(eligible, key=lambda p: p["fpr"])
    return {"tar": tar, "far": best["fpr"], "threshold": best["threshold"]}


def brier_score(y_true: Sequence[int], probabilities: Sequence[float]) -> float:
    y = np.asarray(y_true, dtype=np.float64)
    p = np.clip(np.asarray(probabilities, dtype=np.float64), 0.0, 1.0)
    return float(np.mean((p - y) ** 2))


def cluster_metrics(assignments: Dict[str, str], truth: Dict[str, str]) -> Dict[str, float]:
    ids = sorted(set(assignments) & set(truth))
    if not ids:
        return {"cluster_purity": 0.0, "false_merge_rate": 0.0, "false_split_rate": 0.0}
    clusters: Dict[str, List[str]] = {}
    for image_id in ids:
        clusters.setdefault(assignments[image_id], []).append(image_id)
    correct = 0
    pairs = 0
    false_merges = 0
    false_splits = 0
    truth_to_clusters: Dict[str, set[str]] = {}
    for cluster_id, members in clusters.items():
        counts: Dict[str, int] = {}
        for image_id in members:
            counts[truth[image_id]] = counts.get(truth[image_id], 0) + 1
            truth_to_clusters.setdefault(truth[image_id], set()).add(cluster_id)
        correct += max(counts.values())
        for i in range(len(members)):
            for j in range(i + 1, len(members)):
                pairs += 1
                if truth[members[i]] != truth[members[j]]:
                    false_merges += 1
    for cluster_ids in truth_to_clusters.values():
        if len(cluster_ids) > 1:
            false_splits += len(cluster_ids) - 1
    return {
        "cluster_purity": correct / max(1, len(ids)),
        "false_merge_rate": false_merges / max(1, pairs),
        "false_split_rate": false_splits / max(1, len(truth_to_clusters)),
    }
